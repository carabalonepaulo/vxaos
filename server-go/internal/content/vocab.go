// Package content loads the source-of-truth content files and generates the
// Ruby modules that are embedded in the client's Scripts.rvdata2.
package content

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"os"
	"regexp"
	"strings"
	"unicode/utf8"
)

// VocabEntry is one translation row.
type VocabEntry struct {
	Key  string
	Text string
}

var vocabKeyRE = regexp.MustCompile(`^[A-Z][A-Za-z0-9_]*$`)

// LoadVocabCSV reads a key,text CSV file. The first row may be a header named
// "key,text". Duplicate keys are allowed; the last value wins, matching Ruby's
// constant redefinition. The order of first occurrence is preserved.
func LoadVocabCSV(path string) ([]VocabEntry, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	r := csv.NewReader(f)
	r.FieldsPerRecord = 2
	rows, err := r.ReadAll()
	if err != nil {
		return nil, fmt.Errorf("content: %s: %w", path, err)
	}
	if len(rows) == 0 {
		return nil, fmt.Errorf("content: %s: empty vocab file", path)
	}
	start := 0
	if strings.EqualFold(strings.TrimSpace(rows[0][0]), "key") && strings.EqualFold(strings.TrimSpace(rows[0][1]), "text") {
		start = 1
	}
	index := make(map[string]int)
	out := make([]VocabEntry, 0, len(rows)-start)
	for i := start; i < len(rows); i++ {
		key := strings.TrimSpace(rows[i][0])
		text := rows[i][1]
		if key == "" {
			return nil, fmt.Errorf("content: %s:%d: empty key", path, i+1)
		}
		if !vocabKeyRE.MatchString(key) {
			return nil, fmt.Errorf("content: %s:%d: invalid Ruby constant %q", path, i+1, key)
		}
		if !utf8.ValidString(text) {
			return nil, fmt.Errorf("content: %s:%d: invalid UTF-8", path, i+1)
		}
		if at, ok := index[key]; ok {
			out[at].Text = text
			continue
		}
		index[key] = len(out)
		out = append(out, VocabEntry{Key: key, Text: text})
	}
	return out, nil
}

// RenderVocab produces the [VS] Vocab Ruby module.
func RenderVocab(entries []VocabEntry) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("# Generated by vxaos-content. Do not edit.\n")
	b.WriteString("module Vocab\n\n")
	for _, e := range entries {
		if !vocabKeyRE.MatchString(e.Key) {
			return nil, fmt.Errorf("content: invalid vocab key %q", e.Key)
		}
		s, err := rubyString(e.Text)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "  %s = %s\n", e.Key, s)
	}
	b.WriteString("\nend\n")
	return b.Bytes(), nil
}

// rubyString renders a UTF-8 string literal without allowing Ruby
// interpolation. A double-quoted string is used so newlines can be escaped; '#'
// is escaped to keep "#{...}" literal.
func rubyString(s string) (string, error) {
	if !utf8.ValidString(s) {
		return "", fmt.Errorf("content: invalid UTF-8 string")
	}
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case '#':
			b.WriteString(`\#`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String(), nil
}
