package content

import (
	"bytes"
	"fmt"
	"os"
	"regexp"

	"github.com/BurntSushi/toml"
)

// EnumsSchemaVersion is the supported schema version of enums.toml.
const EnumsSchemaVersion = 1

var enumNameRE = regexp.MustCompile(`^[A-Z][A-Za-z0-9_]*$`)

// EnumValue is one named number in an enum group.
type EnumValue struct {
	Name  string `toml:"name"`
	Value int    `toml:"value"`
}

// EnumGroup is one Ruby module under Enums.
type EnumGroup struct {
	Name   string      `toml:"name"`
	Values []EnumValue `toml:"values"`
}

// ProtocolEnums holds the protocol v2 wire values. They are validated against
// the Go server and the client patch; they are not rendered into [VS] Enums.
type ProtocolEnums struct {
	Client map[string]int `toml:"client"`
	Server map[string]int `toml:"server"`
}

// EnumsFile is the decoded content/enums.toml.
type EnumsFile struct {
	SchemaVersion int           `toml:"schema_version"`
	Enums         []EnumGroup   `toml:"enum"`
	Protocol      ProtocolEnums `toml:"protocol"`
}

// LoadEnums reads and validates content/enums.toml.
func LoadEnums(path string) (*EnumsFile, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var file EnumsFile
	if err := toml.Unmarshal(data, &file); err != nil {
		return nil, fmt.Errorf("content: %s: %w", path, err)
	}
	if err := file.Validate(); err != nil {
		return nil, fmt.Errorf("content: %s: %w", path, err)
	}
	return &file, nil
}

// Validate checks names, duplicates and explicit values.
func (f *EnumsFile) Validate() error {
	if f.SchemaVersion != EnumsSchemaVersion {
		return fmt.Errorf("unsupported enums schema version %d (want %d)", f.SchemaVersion, EnumsSchemaVersion)
	}
	if len(f.Enums) == 0 {
		return fmt.Errorf("no enum groups")
	}
	seenGroups := make(map[string]bool, len(f.Enums))
	for _, group := range f.Enums {
		if !enumNameRE.MatchString(group.Name) {
			return fmt.Errorf("invalid enum name %q", group.Name)
		}
		if seenGroups[group.Name] {
			return fmt.Errorf("duplicate enum %q", group.Name)
		}
		seenGroups[group.Name] = true
		if len(group.Values) == 0 {
			return fmt.Errorf("enum %q has no values", group.Name)
		}
		seenNames := make(map[string]bool, len(group.Values))
		seenValues := make(map[int]bool, len(group.Values))
		for _, value := range group.Values {
			if !enumNameRE.MatchString(value.Name) {
				return fmt.Errorf("enum %s has invalid constant %q", group.Name, value.Name)
			}
			if seenNames[value.Name] {
				return fmt.Errorf("enum %s has duplicate constant %q", group.Name, value.Name)
			}
			seenNames[value.Name] = true
			if seenValues[value.Value] {
				return fmt.Errorf("enum %s has duplicate value %d", group.Name, value.Value)
			}
			seenValues[value.Value] = true
		}
	}
	if len(f.Protocol.Client) == 0 || len(f.Protocol.Server) == 0 {
		return fmt.Errorf("protocol client/server opcode tables are required")
	}
	for prefix, table := range map[string]map[string]int{"client": f.Protocol.Client, "server": f.Protocol.Server} {
		seenNames := make(map[string]bool, len(table))
		seenValues := make(map[int]bool, len(table))
		for name, value := range table {
			if !enumNameRE.MatchString(name) {
				return fmt.Errorf("protocol %s has invalid name %q", prefix, name)
			}
			if seenNames[name] {
				return fmt.Errorf("protocol %s has duplicate name %q", prefix, name)
			}
			seenNames[name] = true
			if seenValues[value] {
				return fmt.Errorf("protocol %s has duplicate value %d", prefix, value)
			}
			seenValues[value] = true
		}
	}
	return nil
}

// RenderEnums produces the [VS] Enums Ruby module.
func RenderEnums(file *EnumsFile) ([]byte, error) {
	if err := file.Validate(); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("# Generated by vxaos-content from enums.toml. Do not edit.\n")
	b.WriteString("module Enums\n\n")
	for _, group := range file.Enums {
		fmt.Fprintf(&b, "  %s = Module.new\n", group.Name)
		for _, value := range group.Values {
			fmt.Fprintf(&b, "  %s.const_set(:%s, %d)\n", group.Name, value.Name, value.Value)
		}
		b.WriteString("\n")
	}
	b.WriteString("end\n")
	return b.Bytes(), nil
}
