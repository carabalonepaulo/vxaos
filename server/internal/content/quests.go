package content

import (
	"bytes"
	"fmt"
	"os"

	"github.com/BurntSushi/toml"
)

// Quest is one entry of the ordered quest table. Index 0 is quest id 0;
// event scripts address it with a one-based id.
type Quest struct {
	Name           string `toml:"name"`
	Desc           string `toml:"desc"`
	SwitchID       int    `toml:"switch_id"`
	VariableID     int    `toml:"variable_id"`
	VariableAmount int    `toml:"variable_amount"`
	ItemID         int    `toml:"item_id"`
	ItemKind       int    `toml:"item_kind"`
	ItemAmount     int    `toml:"item_amount"`
	EnemyID        int    `toml:"enemy_id"`
	EnemyAmount    int    `toml:"enemy_amount"`
	RewEXP         int    `toml:"rew_exp"`
	RewGold        int    `toml:"rew_gold"`
	RewItemID      int    `toml:"rew_item_id"`
	RewItemKind    int    `toml:"rew_item_kind"`
	RewItemAmount  int    `toml:"rew_item_amount"`
	Repeat         bool   `toml:"repeat"`
}

type questsFile struct {
	Quests []Quest `toml:"quest"`
}

// LoadQuests reads content/quests.toml.
func LoadQuests(path string) ([]Quest, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var file questsFile
	if err := toml.Unmarshal(data, &file); err != nil {
		return nil, fmt.Errorf("content: %s: %w", path, err)
	}
	for i, q := range file.Quests {
		if err := validateQuest(q); err != nil {
			return nil, fmt.Errorf("content: %s quest %d: %w", path, i, err)
		}
	}
	return file.Quests, nil
}

func validateQuest(q Quest) error {
	if q.Name == "" {
		return fmt.Errorf("empty name")
	}
	if q.SwitchID < 0 || q.VariableID < 0 || q.ItemID < 0 || q.EnemyID < 0 {
		return fmt.Errorf("negative id")
	}
	if q.ItemKind < 0 || q.ItemKind > 3 {
		return fmt.Errorf("item_kind %d out of range", q.ItemKind)
	}
	if q.RewItemKind < 0 || q.RewItemKind > 3 {
		return fmt.Errorf("rew_item_kind %d out of range", q.RewItemKind)
	}
	if q.VariableAmount < 0 || q.ItemAmount < 0 || q.EnemyAmount < 0 || q.RewItemAmount < 0 {
		return fmt.Errorf("negative amount")
	}
	if q.RewEXP < 0 || q.RewGold < 0 {
		return fmt.Errorf("negative reward")
	}
	return nil
}

// RenderQuests produces the [VS] Quests Ruby module.
func RenderQuests(quests []Quest) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("# Generated by vxaos-content. Do not edit.\n")
	b.WriteString("module Quests\n\n")
	b.WriteString("  DATA = []\n")
	for i, q := range quests {
		if err := validateQuest(q); err != nil {
			return nil, fmt.Errorf("content: quest %d: %w", i, err)
		}
		name, err := rubyString(q.Name)
		if err != nil {
			return nil, err
		}
		desc, err := rubyString(q.Desc)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, `
  DATA << {
    :name            => %s,
    :desc            => %s,
    :switch_id       => %d,
    :variable_id     => %d,
    :variable_amount => %d,
    :item_id         => %d,
    :item_kind       => %d,
    :item_amount     => %d,
    :enemy_id        => %d,
    :enemy_amount    => %d,
    :rew_exp         => %d,
    :rew_gold        => %d,
    :rew_item_id     => %d,
    :rew_item_kind   => %d,
    :rew_item_amount => %d,
    :repeat          => %t
  }
`, name, desc, q.SwitchID, q.VariableID, q.VariableAmount, q.ItemID, q.ItemKind, q.ItemAmount,
			q.EnemyID, q.EnemyAmount, q.RewEXP, q.RewGold, q.RewItemID, q.RewItemKind, q.RewItemAmount, q.Repeat)
	}
	b.WriteString("\nend\n")
	return b.Bytes(), nil
}
